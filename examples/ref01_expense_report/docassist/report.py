"""Render the deliverable: a Markdown reimbursement report built from the run record.

The report is generated by code from the verdict and the answer. The model never
writes the report text, so the report cannot claim a status the runner did not
record. (The completion checker still verifies that, because files can be edited.)
"""

from __future__ import annotations

from typing import Any


def render(run_id: str, claim: dict[str, Any], verdict: dict[str, Any],
           source: dict[str, str] | None) -> str:
    answer = (verdict.get("answer_v1_view") or verdict.get("answer")) if not verdict.get("schema_errors") else None
    lines = [f"# Reimbursement report: claim {claim['claim_id']}", "",
             f"- Run: `{run_id}`",
             f"- Run status: **{verdict['status']}**"]
    if source:
        lines.append(f"- Policy source: `{source['name']}` (sha256 `{source['sha256'][:16]}…`)")
    else:
        lines.append("- Policy source: **not loaded**")
    if verdict["reasons"]:
        lines.append("- Reasons: " + "; ".join(verdict["reasons"]))
    lines.append("")
    claimed = {item["index"]: item for item in claim["items"]}
    if answer:
        lines += ["| Item | Type | Claimed (EUR) | Allowed (EUR) | Policy line | Quoted rule |",
                  "|---|---|---|---|---|---|"]
        for item in answer["items"]:
            source_item = claimed.get(item["index"], {})
            lines.append(f"| {item['index']} | {source_item.get('type', '?')} | "
                         f"{source_item.get('amount', '?')} | {item['allowed']} | "
                         f"{item['rule_line']} | {item['rule_quote']} |")
        lines += ["", f"**Total allowed: {answer['total_allowed']} EUR.** "
                      f"Decision: {answer['decision']}.", ""]
    else:
        lines += ["No valid assessment was produced; nothing may be paid on the basis of this run.", ""]
    if verdict.get("checks"):
        lines += ["## Checks", "", "| Check | Result | Detail |", "|---|---|---|"]
        lines += [f"| {c['check_id']} | {'pass' if c['passed'] else 'FAIL'} | {c['detail']} |"
                  for c in verdict["checks"]]
        lines.append("")
    lines.append("This report was generated by code from the run record. A passed run means "
                 "the stated checks passed; it does not replace the treasurer's judgement on "
                 "items the policy does not cover.")
    return "\n".join(lines) + "\n"
